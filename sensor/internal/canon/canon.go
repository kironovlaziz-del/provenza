// Package canon is the canonical form Provenza signs and hashes - the server's rule
// (json.dumps(value, sort_keys=True, separators=(",", ":")) with ensure_ascii),
// byte for byte. The server hashes what it PARSED from the JSON a client sent,
// so a value is first marshaled as it will be sent, decoded keeping numbers as
// text, and written the way Python writes the parsed value:
//
//	key order  by code point (Go's byte-wise UTF-8 order is the same)
//	strings    everything outside U+0020..U+007E as \uXXXX (lowercase, UTF-16
//	           surrogate pairs), short forms \" \\ \n \r \t \b \f
//	numbers    without "." or "e" a Python int (any size); otherwise a float,
//	           written as Python's repr: 1e-07, 1e-05, 1e+16, 0.0001
//
// sdk/testdata/canonical-vectors.json holds outputs generated by the server;
// sdk/go/canonical.go is the same code for the Go SDK.
package canon

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"math"
	"math/big"
	"sort"
	"strconv"
	"strings"
	"unicode/utf16"
	"unicode/utf8"
)

// Parse decodes JSON keeping numbers as text (json.Number), the form Text writes.
func Parse(raw []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var out any
	if err := dec.Decode(&out); err != nil {
		return nil, err
	}
	if dec.More() {
		return nil, fmt.Errorf("canon: trailing data after the JSON value")
	}
	return out, nil
}

// Of is the parsed form of any Go value (through encoding/json), as the server
// would receive it.
func Of(v any) (any, error) {
	raw, err := json.Marshal(v)
	if err != nil {
		return nil, fmt.Errorf("canon: value has no JSON form: %w", err)
	}
	return Parse(raw)
}

// Text is the canonical text of a parsed value (pure ASCII).
func Text(v any) (string, error) {
	var b strings.Builder
	if err := write(&b, v); err != nil {
		return "", err
	}
	return b.String(), nil
}

// UnicodeText is Text as the server writes it with ensure_ascii=False - what
// a tool definition's digest is taken over (app/services/supply_chain.py
// manifest_digest): characters from U+007F up are written as they are.
func UnicodeText(v any) (string, error) {
	var b strings.Builder
	if err := writeAs(&b, v, true); err != nil {
		return "", err
	}
	return b.String(), nil
}

// Bytes is Text of any Go value.
func Bytes(v any) ([]byte, error) {
	j, err := Of(v)
	if err != nil {
		return nil, err
	}
	s, err := Text(j)
	return []byte(s), err
}

// SHA256 is the hex SHA-256 of the canonical text of a parsed value - the
// server's content_hash.
func SHA256(v any) (string, error) {
	s, err := Text(v)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:]), nil
}

func write(b *strings.Builder, v any) error { return writeAs(b, v, false) }

func writeAs(b *strings.Builder, v any, unicode bool) error {
	switch x := v.(type) {
	case nil:
		b.WriteString("null")
	case bool:
		if x {
			b.WriteString("true")
		} else {
			b.WriteString("false")
		}
	case json.Number:
		s, err := pyNumber(string(x))
		if err != nil {
			return err
		}
		b.WriteString(s)
	case string:
		writeStr(b, x, unicode)
	case []any:
		b.WriteByte('[')
		for i, item := range x {
			if i > 0 {
				b.WriteByte(',')
			}
			if err := writeAs(b, item, unicode); err != nil {
				return err
			}
		}
		b.WriteByte(']')
	case map[string]any:
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		b.WriteByte('{')
		for i, k := range keys {
			if i > 0 {
				b.WriteByte(',')
			}
			writeStr(b, k, unicode)
			b.WriteByte(':')
			if err := writeAs(b, x[k], unicode); err != nil {
				return err
			}
		}
		b.WriteByte('}')
	default:
		return fmt.Errorf("canon: unexpected JSON value %T", v)
	}
	return nil
}

var short = map[rune]string{'"': `\"`, '\\': `\\`, '\n': `\n`, '\r': `\r`, '\t': `\t`, '\b': `\b`, '\f': `\f`}

func writeStr(b *strings.Builder, s string, unicode bool) {
	b.WriteByte('"')
	for _, r := range s {
		if e, ok := short[r]; ok {
			b.WriteString(e)
			continue
		}
		if (r >= 0x20 && r <= 0x7e) || (unicode && r >= 0x7f && r != utf8.RuneError) {
			b.WriteRune(r)
			continue
		}
		if r > 0xFFFF {
			hi, lo := utf16.EncodeRune(r)
			fmt.Fprintf(b, `\u%04x\u%04x`, hi, lo)
			continue
		}
		if r == utf8.RuneError {
			r = 0xFFFD
		}
		fmt.Fprintf(b, `\u%04x`, r)
	}
	b.WriteByte('"')
}

// pyNumber writes a JSON number the way Python writes what json.loads made of it.
func pyNumber(text string) (string, error) {
	if !strings.ContainsAny(text, ".eE") {
		n, ok := new(big.Int).SetString(text, 10) // a Python int: any size, "-0" is 0
		if !ok {
			return "", fmt.Errorf("canon: bad number %q", text)
		}
		return n.String(), nil
	}
	f, err := strconv.ParseFloat(text, 64)
	if err != nil {
		return "", fmt.Errorf("canon: bad number %q", text)
	}
	return pyFloatRepr(f), nil
}

// pyFloatRepr is Python's repr(float): the shortest round-trip digits, fixed
// notation for exponents -4..15, otherwise d.ddde+XX with at least two exponent digits.
func pyFloatRepr(f float64) string {
	if f == 0 {
		if math.Signbit(f) {
			return "-0.0"
		}
		return "0.0"
	}
	sign := ""
	if f < 0 {
		sign, f = "-", -f
	}
	e := strconv.FormatFloat(f, 'e', -1, 64) // d.ddde±XX, the shortest round-trip digits
	mant, expText, _ := strings.Cut(e, "e")
	exp, _ := strconv.Atoi(expText)
	digits := strings.Replace(mant, ".", "", 1)
	digits = strings.TrimRight(digits, "0")
	if digits == "" {
		digits = "0"
	}
	if exp >= -4 && exp < 16 {
		if exp < 0 {
			return sign + "0." + strings.Repeat("0", -exp-1) + digits
		}
		whole, frac := digits, ""
		if len(digits) > exp+1 {
			whole, frac = digits[:exp+1], digits[exp+1:]
		} else {
			whole += strings.Repeat("0", exp+1-len(digits))
		}
		if frac == "" {
			frac = "0"
		}
		return sign + whole + "." + frac
	}
	m := digits[:1]
	if len(digits) > 1 {
		m += "." + digits[1:]
	}
	es := "+"
	if exp < 0 {
		es, exp = "-", -exp
	}
	return fmt.Sprintf("%s%se%s%02d", sign, m, es, exp)
}
