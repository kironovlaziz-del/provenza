/**
 * The canonical form Provenza signs and hashes - the server's rule
 * (backend/app/core/agent_signing.py), reproduced byte for byte:
 *
 *   json.dumps(value, sort_keys=True, separators=(",", ":"))   with ensure_ascii
 *
 * The server hashes what it PARSED from the JSON a client sent, so the value
 * here is first passed through JSON (what JSON.stringify would send), and then
 * written the way Python writes the parsed value. Three places where that
 * differs from JSON.stringify:
 *
 *   key order   Python sorts by code point; JS compares UTF-16 code units
 *               (U+FB33 sorts before U+1F600 in Python, after it in JS)
 *   strings     everything outside U+0020..U+007E is escaped as \uXXXX
 *               (lowercase hex, surrogate pairs), short forms \" \\ \n \r \t \b \f
 *   numbers     a JSON number without "." or "e" is a Python int; any other is
 *               a float, written as Python's repr: 1e-07, 1e-05, 1e+16, 0.0001
 *
 * test/vectors.json holds expected outputs generated by the server's own code.
 */

import { trimEnd, trimStart } from "./text.js";

export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

/** The value as the server will receive it - and refuses what it cannot. */
export function toJson(value: unknown, what = "value"): Json {
  const check = (v: unknown, path: string): void => {
    if (typeof v === "number" && !Number.isFinite(v)) throw new TypeError(`${what}: ${path} is NaN or Infinity`);
    if (typeof v === "bigint") throw new TypeError(`${what}: ${path} is a BigInt (no JSON form)`);
    if (v !== null && typeof v === "object") {
      for (const [k, x] of Object.entries(v as Record<string, unknown>)) check(x, `${path}.${k}`);
    }
  };
  check(value, "$");
  const text = JSON.stringify(value);
  if (text === undefined) throw new TypeError(`${what} has no JSON form`);
  return JSON.parse(text) as Json;
}

const SHORT: Record<string, string> = {'"': '\\"', "\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t", "\b": "\\b", "\f": "\\f"};

function str(s: string): string {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const ch = s[i] as string;
    const code = s.charCodeAt(i);
    if (SHORT[ch] !== undefined) out += SHORT[ch];
    else if (code < 0x20 || code > 0x7e) out += "\\u" + code.toString(16).padStart(4, "0");
    else out += ch;
  }
  return out + '"';
}

/** Python's repr of the float JSON.stringify(x) parses to. */
function pyFloat(text: string): string {
  let sign = "";
  if (text.startsWith("-")) { sign = "-"; text = text.slice(1); }
  const [mant = "", expPart] = text.split("e");
  const exp = expPart === undefined ? 0 : parseInt(expPart, 10);
  const dot = mant.indexOf(".");
  const intLen = dot === -1 ? mant.length : dot;
  let digits = mant.replace(".", "");
  const lead = digits.length - trimStart(digits, "0").length;
  digits = trimEnd(digits.slice(lead), "0");
  if (digits === "") return sign + "0.0";
  const e10 = intLen - 1 - lead + exp;   // value = d.ddd x 10^e10
  if (e10 >= -4 && e10 < 16) {
    if (e10 < 0) return `${sign}0.${"0".repeat(-e10 - 1)}${digits}`;
    const whole = digits.slice(0, e10 + 1).padEnd(e10 + 1, "0");
    const frac = digits.slice(e10 + 1);
    return `${sign}${whole}.${frac || "0"}`;
  }
  const m = digits.length > 1 ? `${digits[0]}.${digits.slice(1)}` : digits;
  return `${sign}${m}e${e10 < 0 ? "-" : "+"}${String(Math.abs(e10)).padStart(2, "0")}`;
}

function num(x: number): string {
  const text = JSON.stringify(x);
  return /[.e]/.test(text) ? pyFloat(text) : text;
}

function byCodePoint(a: string, b: string): number {
  const x = Array.from(a), y = Array.from(b);
  for (let i = 0; i < Math.min(x.length, y.length); i++) {
    const d = (x[i] as string).codePointAt(0)! - (y[i] as string).codePointAt(0)!;
    if (d !== 0) return d;
  }
  return x.length - y.length;
}

function write(v: Json): string {
  if (v === null) return "null";
  if (v === true) return "true";
  if (v === false) return "false";
  if (typeof v === "number") return num(v);
  if (typeof v === "string") return str(v);
  if (Array.isArray(v)) return "[" + v.map(write).join(",") + "]";
  const keys = Object.keys(v).sort(byCodePoint);
  return "{" + keys.map((k) => str(k) + ":" + write(v[k] as Json)).join(",") + "}";
}

/** The canonical text of a value (pure ASCII). */
export function canonical(value: unknown): string {
  return write(toJson(value));
}
