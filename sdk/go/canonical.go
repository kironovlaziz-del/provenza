package provenza

// The canonical form Provenza signs and hashes - the server's rule
// (json.dumps(value, sort_keys=True, separators=(",", ":")) with ensure_ascii),
// byte for byte. The server hashes what it PARSED from the JSON a client sent,
// so a value is first marshaled as it will be sent, decoded keeping numbers as
// text, and written the way Python writes the parsed value:
//
//	key order  by code point (Go's byte-wise UTF-8 order is the same)
//	strings    everything outside U+0020..U+007E as \uXXXX (lowercase, UTF-16
//	           surrogate pairs), short forms \" \\ \n \r \t \b \f
//	numbers    without "." or "e" a Python int (any size); otherwise a float,
//	           written as Python's repr: 1e-07, 1e-05, 1e+16, 0.0001
//
// sdk/testdata/canonical-vectors.json holds outputs generated by the server.

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"math/big"
	"sort"
	"strconv"
	"strings"
	"unicode/utf16"
	"unicode/utf8"
)

// toJSON is the value as the server will receive it, with numbers as json.Number.
func toJSON(v any) (any, error) {
	raw, err := json.Marshal(v)
	if err != nil {
		return nil, fmt.Errorf("provenza: value has no JSON form: %w", err)
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var out any
	if err := dec.Decode(&out); err != nil {
		return nil, err
	}
	return out, nil
}

// Canonical returns the canonical text of v (pure ASCII). Values that json.Marshal
// refuses (NaN, Inf, channels, ...) are an error.
func Canonical(v any) (string, error) {
	j, err := toJSON(v)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	if err := write(&b, j); err != nil {
		return "", err
	}
	return b.String(), nil
}

func write(b *strings.Builder, v any) error {
	switch x := v.(type) {
	case nil:
		b.WriteString("null")
	case bool:
		if x {
			b.WriteString("true")
		} else {
			b.WriteString("false")
		}
	case json.Number:
		s, err := pyNumber(string(x))
		if err != nil {
			return err
		}
		b.WriteString(s)
	case string:
		writeString(b, x)
	case []any:
		b.WriteByte('[')
		for i, item := range x {
			if i > 0 {
				b.WriteByte(',')
			}
			if err := write(b, item); err != nil {
				return err
			}
		}
		b.WriteByte(']')
	case map[string]any:
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		b.WriteByte('{')
		for i, k := range keys {
			if i > 0 {
				b.WriteByte(',')
			}
			writeString(b, k)
			b.WriteByte(':')
			if err := write(b, x[k]); err != nil {
				return err
			}
		}
		b.WriteByte('}')
	default:
		return fmt.Errorf("provenza: unexpected JSON value %T", v)
	}
	return nil
}

var short = map[rune]string{'"': `\"`, '\\': `\\`, '\n': `\n`, '\r': `\r`, '\t': `\t`, '\b': `\b`, '\f': `\f`}

func writeString(b *strings.Builder, s string) {
	b.WriteByte('"')
	for _, r := range s {
		if e, ok := short[r]; ok {
			b.WriteString(e)
			continue
		}
		if r >= 0x20 && r <= 0x7e {
			b.WriteRune(r)
			continue
		}
		if r > 0xFFFF {
			hi, lo := utf16.EncodeRune(r)
			fmt.Fprintf(b, `\u%04x\u%04x`, hi, lo)
			continue
		}
		if r == utf8.RuneError {
			r = 0xFFFD
		}
		fmt.Fprintf(b, `\u%04x`, r)
	}
	b.WriteByte('"')
}

// pyNumber writes a JSON number the way Python writes what json.loads made of it.
func pyNumber(text string) (string, error) {
	if !strings.ContainsAny(text, ".eE") {
		n, ok := new(big.Int).SetString(text, 10) // a Python int: any size, "-0" is 0
		if !ok {
			return "", fmt.Errorf("provenza: bad number %q", text)
		}
		return n.String(), nil
	}
	f, err := strconv.ParseFloat(text, 64)
	if err != nil {
		return "", fmt.Errorf("provenza: bad number %q", text)
	}
	return pyFloatRepr(f), nil
}

// pyFloatRepr is Python's repr(float): the shortest round-trip digits, fixed
// notation for exponents -4..15, otherwise d.ddde+XX with at least two exponent digits.
func pyFloatRepr(f float64) string {
	if f == 0 {
		if math.Signbit(f) {
			return "-0.0"
		}
		return "0.0"
	}
	sign := ""
	if f < 0 {
		sign, f = "-", -f
	}
	e := strconv.FormatFloat(f, 'e', -1, 64) // d.ddde±XX, the shortest round-trip digits
	mant, expText, _ := strings.Cut(e, "e")
	exp, _ := strconv.Atoi(expText)
	digits := strings.Replace(mant, ".", "", 1)
	digits = strings.TrimRight(digits, "0")
	if digits == "" {
		digits = "0"
	}
	if exp >= -4 && exp < 16 {
		if exp < 0 {
			return sign + "0." + strings.Repeat("0", -exp-1) + digits
		}
		whole, frac := digits, ""
		if len(digits) > exp+1 {
			whole, frac = digits[:exp+1], digits[exp+1:]
		} else {
			whole += strings.Repeat("0", exp+1-len(digits))
		}
		if frac == "" {
			frac = "0"
		}
		return sign + whole + "." + frac
	}
	m := digits[:1]
	if len(digits) > 1 {
		m += "." + digits[1:]
	}
	es := "+"
	if exp < 0 {
		es, exp = "-", -exp
	}
	return fmt.Sprintf("%s%se%s%02d", sign, m, es, exp)
}
