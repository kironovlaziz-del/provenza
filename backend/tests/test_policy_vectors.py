"""
sdk/testdata/policy-vectors.json is what the server decides
(app/pvp/bundle_eval.py, generated by scripts/policy_vectors.py); the Go
enforcement point (proxy/internal/policy) must decide the same. The file must
be up to date with the code, and a few decisions are pinned here by hand so a
regression in the evaluator cannot silently rewrite its own expectations.
"""

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("policy_vectors_script", ROOT / "backend" / "scripts" / "policy_vectors.py")
script = importlib.util.module_from_spec(spec)
spec.loader.exec_module(script)


def test_the_vectors_file_is_what_the_server_decides():
    committed = json.loads((ROOT / "sdk" / "testdata" / "policy-vectors.json").read_text(encoding="utf-8"))
    assert committed == json.loads(json.dumps(script.build(), ensure_ascii=False)), \
        "run: python scripts/policy_vectors.py"


def test_pinned_decisions():
    got = {c["name"]: c["expect"] for c in script.build()["cases"]}
    assert got["allowed"]["decision"] == "allowed"
    assert got["not in the bundle"]["decision"] == "denied"
    assert got["another key"]["decision"] == "denied"
    assert got["expired"]["decision"] == "denied"
    assert got["capability the registry requires"]["reason"] == "Capability escalation detected: refunds"
    assert got["team approval pattern"]["decision"] == "pending_approval"
    assert got["deny beats approval"]["decision"] == "denied"
    assert got["proxy request"]["decision"] == "allowed"
    assert got["proxy body"]["decision"] == "denied"
    assert got["starts_with normalised path"]["decision"] == "denied"
    assert got["equals: 1 is 1.0"]["decision"] == "allowed"
